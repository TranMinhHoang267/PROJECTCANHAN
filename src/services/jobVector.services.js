const prisma = require("../config/prisma");
const crypto = require("crypto");
/**
 * Service contains logic for:
 * - Chunking (data after cleaning).
 * - Vectorization (using SBERT).
 * - Storing and retrieving vectors from the database.
 */

const { cleaningJob } = require("../utils/preprocessing/textCleaner");
const { arrayChunking } = require("../utils/preprocessing/textChunking");
const { textEmbedding } = require("../utils/preprocessing/textEmbedding");
const {
  textStandardization,
} = require("../utils/preprocessing/textStandardization");


// --- HÀM HỖ TRỢ RETRY ---
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function retryEmbedding(chunk, retries = 3) {
  for (let i = 0; i < retries; i++) {
    try {
      const embedding = await textEmbedding(chunk);
      if (embedding) return embedding;
      throw new Error("Embedding returned empty");
    } catch (error) {
      if (i === retries - 1) {
        console.error(`Thất bại sau ${retries} lần thử cho đoạn văn bản.`);
        throw error;
      }
      const waitTime = Math.pow(2, i) * 2000; // Đợi 2s, 4s, 8s
      console.warn(`Thử lại lần ${i + 1} sau ${waitTime}ms do lỗi API...`);
      await delay(waitTime);
    }
  }
}

/**
 * @typedef {Object} ProcessedChunk
 * @property {string} content - raw text chunk after cleaning and chunking
 * @property {number[]} embedding - vector representation of the chunk generated by the embedding model
 * @property {number} index - the order of the chunk in the original text (starting from 0)
 */

/**
 * @param {string} jobId - job ID
 * @param {string} userId - user ID
 * @param {string} companyId - company ID
 * @param {ProcessedChunk[]} processedChunks - An array of objects containing chunk content, its embedding, and index
 */
async function _storeNewJobVector(jobId, userId, companyId, processedChunks) {
  
  if (!jobId || !processedChunks || !Array.isArray(processedChunks)) {
    throw new Error("Invalid input for storeJobVector");
  }

  /**
   * Storing each chunk and its embedding in the database. We use a transaction to ensure that all chunks for a job are stored together, maintaining data integrity.
   * Each chunk is associated with the job ID, and we also store the index to keep track of the original order of the chunks. This will be important for reconstructing the text or for any operations that require understanding the sequence of the chunks.
   * The embedding is stored as a JSON string since it is an array of numbers, which allows us to easily retrieve and use it later for similarity searches or other vector-based operations.
   */

  try {
    await prisma.$transaction(async (tx) => {
      for (const chunk of processedChunks) {
        const vectorStr = `[${chunk.embedding.join(",")}]`;
        const id = crypto.randomUUID(); // Generate a unique ID for each chunk
        await tx.$executeRaw`
          INSERT INTO "job_vectors" ("id", "job_id", "user_id", "company_id", content, embedding,created_at,updated_at)
          VALUES ( ${id},${jobId}, ${userId}, ${companyId}, ${chunk.content}, ${vectorStr}::vector, NOW(), NOW())
        `;
      }
      await tx.job.update({
        where: { id: jobId },
        data: { vectorStatus: "COMPLETED" },
      });
    });
  } catch (error) {
    console.error(`Lỗi vector hóa Job ${jobId}:`, error);
    await prisma.job.update({
      where: { id: jobId },
      data: { vectorStatus: "FAILED" },
    });
    throw error;
  }
}

/**
 * @param {string} jobId - job ID
 * @param {string} userId - user ID
 * @param {*} companyId
 * @param {ProcessedChunk[]} processedChunks - An array of objects containing chunk content, its embedding, and index
 */
async function updateExistingJobVector(
  jobId,
  userId,
  companyId,
  processedChunks,
) {
  if (!jobId || !processedChunks || !Array.isArray(processedChunks)) {
    throw new Error("Invalid input for storeJobVector");
  }

  try {
    await prisma.$transaction(async (tx) => {
      // delete existing chunks for the job before updating with new chunks to avoid duplication and maintain data integrity
      await tx.jobVectors.deleteMany({
        where: { jobId: jobId },
      });

      // insert new chunks with updated content and embeddings
      for (const chunk of processedChunks) {
        const vectorStr = `[${chunk.embedding.join(",")}]`;
        const id = crypto.randomUUID(); // Generate a unique ID for each chunk
        await tx.$executeRaw`
          INSERT INTO "job_vectors" ("id", "job_id","user_id", "company_id", content, embedding,created_at,updated_at)
          VALUES ( ${id}, ${jobId}, ${userId}, ${companyId}, ${chunk.content}, ${vectorStr}::vector, NOW(), NOW())
        `;
      }
      await tx.job.update({
        where: { id: jobId },
        data: { vectorStatus: "COMPLETED" },
      });
    });
  } catch (error) {
    console.error(`Lỗi cập nhật vector hóa Job ${jobId}:`, error);
    await prisma.job.update({
      where: { id: jobId },
      data: { vectorStatus: "FAILED" },
    });
    throw error;
  }
}

/**
 * @param {import('@prisma/client').Job} job - job object
 * @param {string} userId - user ID
 */
async function processAndStoreJobVector(job, userId) {
  // console.log("DEBUG Background Job userId:", userId); // Nếu log ra undefined, nghĩa là service chưa nhận được biến
  // Step 1: Clean
  const cleanedText = cleaningJob(job);
  if (!cleanedText) return;

  // Step 2: Standardize
  let standardizedText = cleanedText.map(item => textStandardization(item)).filter(Boolean);

  // Step 3: Chunk
  let chunks = arrayChunking(standardizedText);
  if (chunks.length === 0) return;

  // Step 4: Generate embeddings với cơ chế RETRY
  let chunkEmbeddings = [];
  for (const chunk of chunks) {
    // Gọi hàm có retry ở đây
    const embedding = await retryEmbedding(chunk); 
    chunkEmbeddings.push(embedding);
  }

  // Step 5 & 6: Xử lý và lưu DB (Logic cũ của bạn)
  const processedChunks = chunks.map((chunk, index) => {
    const embeddingArray = Array.isArray(chunkEmbeddings[index])
      ? chunkEmbeddings[index]
      : Array.from(chunkEmbeddings[index].data);

    return { content: chunk, embedding: embeddingArray, index };
  });

  const existingChunks = await prisma.jobVectors.findMany({ where: { jobId: job.id } });

  if (existingChunks.length === 0) {
    await _storeNewJobVector(job.id, userId, job.companyId, processedChunks);
  } else {
    await updateExistingJobVector(job.id, userId, job.companyId, processedChunks);
  }
}

